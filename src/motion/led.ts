const lower: Record<string, string> = { i: 'İ', ı: 'I', ç: 'Ç', ğ: 'Ğ', ö: 'Ö', ş: 'Ş', ü: 'Ü' };
const up = (s: string) => [...s].map((c) => lower[c] ?? c.toUpperCase()).join('');

/** Glyph bitmaps (35 chars, row-major) for a string. */
export function glyphs(text: string) {
  return [...up(text)].map((c) => {
    const g = G[c] ?? G[' '];
    return g.length === 35 ? g : (g + '.'.repeat(35)).slice(0, 35);
  });
}

/** SVG markup for a LED word. Unlit dots stay faintly visible, like a real matrix. */
export function ledSVG(text: string, { cls = 'led', min = 0 }: { cls?: string; min?: number } = {}) {
  const gs = glyphs(text.padStart(min, ' '));
  const w = gs.length * 6 - 1;
  let dots = '';
  gs.forEach((g, i) => {
    for (let k = 0; k < 35; k++) {
      const x = i * 6 + (k % 5) + 0.5;
      const y = Math.floor(k / 5) + 0.5;
      dots += `<circle cx="${x}" cy="${y}" r="0.36"${g[k] === '#' ? ' class="on"' : ''}/>`;
    }
  });
  return `<svg class="${cls}" viewBox="0 0 ${w} 7" width="${w}" height="7" aria-hidden="true" focusable="false">${dots}</svg>`;
}
